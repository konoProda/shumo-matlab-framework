function pv10 = func_interp_q3(fc_hour, nSlot)
%FUNC_INTERP_Q3  整点光伏预报 → 10 分钟预报（线性插值）
%
%   相邻整点预测值 P_h、P_{h+1} 之间线性过渡（C5 = B）：
%       P_{h,m} = P_h + (m/6) * (P_{h+1} - P_h)，m = 0..5
%   槽 [h:00,h:10) 取 m = 0（即 P_h），槽 [h:50,(h+1):00) 取 m = 5。
%   小时序号自**发布时刻**起算：各阶段待解区间的首槽恰为该阶段的发布时刻，
%   故从"预报1小时"起取即可（6:00 阶段的 [06:00,07:00) 用预报1小时，而不是预报7小时）。
%   段末槽需 P_{h+1} 而数据只给到"预报24小时"，末位按 P_24 = P_23 平延
%   （仅 0:00 阶段整天求解时会触及，该槽恒为夜间零值，不影响结果）。
%
%   输入  fc_hour  1×24 该发布时刻的整点预报（预报1..24小时，kW）
%         nSlot    待解区间的槽数（整天 144 / 6:00 起 108 / 12:00 起 72 / 18:00 起 36）
%   输出  pv10     1×nSlot 该区间的 10 分钟光伏预测功率 kW

fc_hour = fc_hour(:).';
t0 = 0:nSlot-1;
h = floor(t0 / 6);                      % 相对发布时刻的小时序号
m = mod(t0, 6);                         % 小时内第几个 10 分钟

p_lo = fc_hour(h + 1);                  % P_h
p_hi = fc_hour(min(h + 2, 24));         % P_{h+1}；末位平延 P_24 = P_23

pv10 = p_lo + (m / 6) .* (p_hi - p_lo);

end
