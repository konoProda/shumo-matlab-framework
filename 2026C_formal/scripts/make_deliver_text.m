% make_deliver_text.m —— 由正式结果自动生成四份交付说明文本
%
%   每份说明只写三件事（按交付规范）：算的是什么 / 按什么思路实现 / 得到什么结果。
%   正文为自然段落，**不出现运行入口、命令行、目录树**；所有数字均从结果文件现取，
%   保证与结果表一致（数字零虚构）。
%   输出到 scripts/deliver_text/qX.txt，再由 pack_deliver.sh 转成 docx。
%
%   ★ 编写约定：每个段落写成**单行字符串**。不要用 "字符串 '…' 续行 '…'" 的写法——
%     MATLAB 会把相邻的两个字符串字面量当成两个参数，直接在解析期报错（本轮踩过两次）。
%
%   用法：matlab -batch "run('scripts/make_deliver_text.m')"

PROJ_ROOT = fullfile(fileparts(mfilename('fullpath')), '..');
addpath(genpath(fullfile(PROJ_ROOT, 'src')));
OUT  = fullfile(PROJ_ROOT, 'outputs');
TXT  = fullfile(PROJ_ROOT, 'scripts', 'deliver_text');
if exist(TXT, 'dir') ~= 7; mkdir(TXT); end
fmt  = @(x) sprintf('%.0f', round(x));
fmt2 = @(x) sprintf('%.2f', x);
w    = @(f, s) fprintf(f, '%s\n', s);

%% ---------- 问题一 ----------
S1  = load(fullfile(OUT, 'final_results_q1.mat'));
fid = fopen(fullfile(TXT, 'q1.txt'), 'w', 'n', 'UTF-8');
w(fid, '# 算的是什么');
w(fid, '本程序解决题目第一问：在分时电价与光伏出力已知的条件下，为微网制定一天的购电与储能充放电计划，使全天购电费用最小。一天被划分为 144 个 10 分钟时段，每个时段决策从外部电网购入的正常电量、储能充电量、放电量，以及光伏的上网与弃光安排，并允许在供电不足时以高价紧急购电兜底。');
w(fid, '# 按什么思路实现');
w(fid, '把"光伏优先供负荷、计划购电补足、不足先放电、再紧急购电；负荷满足后光伏余电优先充电、其次用剩余计划购电充电"这套优先级写成显式分流的线性约束，连同储能电量递推、充放电功率上下限、储能电量上下限、同一时段不得同时充放电等物理条件一起构成混合整数线性规划，调用分支定界求解器求全局最优。由于分流优先级被显式建模，模型解出的结果与按规则逐槽执行的结果逐槽一致。');
w(fid, '# 得到什么结果');
w(fid, sprintf('全年最优购电费用为 %s 元。程序同时输出逐槽的购电计划、储能充放电量与储电量轨迹，以及全天购电量与购电费，并按题目要求的四项内容组织成结果表。', fmt2(S1.Z)));
w(fid, sprintf('模型检查项全部通过：能量平衡最大残差 %.2e，储能递推最大残差 %.2e，且同一时段充放电量之积恒为 0。', S1.rep.total_bal, S1.rep.state_resid));
fclose(fid);

%% ---------- 问题二 ----------
fid = fopen(fullfile(TXT, 'q2.txt'), 'w', 'n', 'UTF-8');
w(fid, '# 算的是什么');
w(fid, '本程序解决题目第二问：未来负荷与光伏出力并不知道，只能依据历史数据预测。程序在每天零时先做预测，再据此制定当天的购电与储能计划，并使在预测不确定下的期望费用最小。');
w(fid, '# 按什么思路实现');
w(fid, '预测环节采用同周期回溯：取历史上与目标日同一星期的最近若干天求平均作为基础预测，再用最近若干天同时段的平均预测误差做逐小时偏差校正。由于预测必然有误差，程序把过去的预测误差整理成历史误差日，每天从中随机抽取若干天构造若干套可能出现的负荷与光伏情景，在这些情景上求一个两阶段随机规划：第一阶段只确定当天对外的购电计划（该计划对所有情景相同，因为制定计划时并不知道当天究竟是哪一套情景），第二阶段针对每一套情景安排储能充放电与紧急购电。为避免模型把当天结束当作终点而错误放空储能，优化视野取七天，用后续六天的费用估计当天日末储电量的价值。');
w(fid, '# 得到什么结果');
if exist(fullfile(OUT,'final_results_q2c_L2.mat'), 'file')
    r2 = load(fullfile(OUT,'final_results_q2c_L2.mat'), 'res').res;
    [~,~,~,dl2] = func_read_q2(PROJ_ROOT);
    wi = (find(dl2 == datetime(2025,2,1)):numel(dl2)).';   % 报送窗口，按日期求（不依赖结果字段）
    w(fid, sprintf('在报送窗口内，采用七天滚动随机优化得到的购电总费用为 %s 元，其中正常购电与调整费用 %s 元、紧急购电费用 %s 元，紧急购电量 %s 千瓦时，全年弃光 %s 千瓦时。', fmt2(sum(r2.cost(wi))), fmt2(sum(r2.cost_plan(wi))), fmt2(sum(r2.cost_em(wi))), fmt(sum(r2.em_m(wi,:),'all')), fmt(sum(r2.curt_m(wi,:),'all'))));
    w(fid, '程序同时给出不考虑预测不确定性时的理想信息基准，两者之差即为预测不确定性所带来的代价。');
else
    w(fid, '（结果文件尚未生成，数字待补）');
end
fclose(fid);

%% ---------- 问题三 ----------
fid = fopen(fullfile(TXT, 'q3.txt'), 'w', 'n', 'UTF-8');
w(fid, '# 算的是什么');
w(fid, '本程序解决题目第三问：题目除零时外，还在六时、十二时、十八时各发布一次未来 24 小时的光伏预报。程序在保持负荷预测不变的前提下，用每次最新发布的光伏预报重新优化尚未执行时段的购电计划，并比较"只用零时预报"到"四个时点全用"四种方案的优劣。');
w(fid, '# 按什么思路实现');
w(fid, '沿用第二问的随机优化框架，把当天近端 24 小时的光伏中心预测换成题目最新发布的那一版预报，24 小时以外仍用自建预测。每到一个更新时点，先执行已过去时段的计划并把实际储能电量带入下一阶段，再重新抽取情景、重新求解、只调整尚未执行的时段。最终生效的购电计划按时间片拼接，调整费用统一相对于当天零时原计划结算一次：调增部分按交易电价的 1.5 倍、调减部分按 0.5 倍。四种方案各自独立跑完一整年，互不共用储能轨迹。');
w(fid, '# 得到什么结果');
names = {'S0','S1','S2','S3'};
labs  = {'只用零时预报','加用六时预报','加用十二时预报','四个时点全用'};
vals  = nan(4,1);
for ii = 1:4
    ff = fullfile(OUT, sprintf('final_results_q3b_%s.mat', names{ii}));
    if exist(ff, 'file'); vals(ii) = load(ff, 's').s.cost_win; end
end
if all(isfinite(vals))
    w(fid, sprintf('报送窗口内四种方案的购电总费用分别为：%s %s 元、%s %s 元、%s %s 元、%s %s 元。', labs{1}, fmt2(vals(1)), labs{2}, fmt2(vals(2)), labs{3}, fmt2(vals(3)), labs{4}, fmt2(vals(4))));
    w(fid, sprintf('费用随预报时点增加而单调下降：加入六时预报的边际收益 %s 元、加入十二时 %s 元、加入十八时 %s 元。说明确实有必要引入其他时刻的光伏预报，但边际收益并不递增。', fmt2(vals(1)-vals(2)), fmt2(vals(2)-vals(3)), fmt2(vals(3)-vals(4))));
    w(fid, '程序对四个题目指定日期给出零时原始计划、四阶段拼接后的最终生效购电量、逐时段紧急购电与储能轨迹，并按题目模板组织成结果表。');
else
    w(fid, '（部分结果文件尚未生成，数字待补）');
end
fclose(fid);

%% ---------- 问题四 ----------
fid = fopen(fullfile(TXT, 'q4.txt'), 'w', 'n', 'UTF-8');
w(fid, '# 算的是什么');
w(fid, '本程序解决题目第四问：当外部电网的实时电价本身也是波动的、且只能预测而不能提前知道时，重新计算第二问与第三问的购电策略。电价属于事前不可知的信息，只有在该时段真正到来之后才能作为实际交易价格使用。');
w(fid, '# 按什么思路实现');
w(fid, '电价预测沿用与负荷、光伏一致的思路：同周期回溯给出基础预测，再用历史同时段误差做偏差校正。负荷误差、光伏误差与电价误差从同一个历史误差日联合抽取，以保留三者之间的相关性；电价情景不做非负截断（真实市场允许负电价）。对应第二问的那份只在零时做一次预测与优化；对应第三问的那份在六时、十二时、十八时用已实现的价格刷新价格预测并重新优化，刷新只作用于当天尚未执行的时段，未来日仍按零时版本处理。两个口径的最终费用一律用附件给出的真实电价重新结算，紧急购电按真实电价的 5 倍计价。');
w(fid, '# 得到什么结果');
% ① Q4-2（对应问题二）② Q4-3（对应问题三）③ Q4-2Ideal（完美价格信息）
% ④ Q4-2P0 ⑤ Q4-3P0（只用中心价格预测、不含价格情景）
nm = {'Q4-2','Q4-3','Q4-2Ideal','Q4-2P0','Q4-3P0'};
c  = nan(1,5);
for ii = 1:numel(nm)
    ff = fullfile(OUT, sprintf('final_results_q4_%s.mat', nm{ii}));
    if exist(ff, 'file'); c(ii) = load(ff, 's').s.cost_win; end
end
if isfinite(c(1)) && isfinite(c(2))
    w(fid, sprintf('报送窗口内，对应第二问的波动电价购电总费用为 %s 元；对应第三问的部分在引入日内价格预测更新后降为 %s 元，降幅 %s 元。', fmt2(c(1)), fmt2(c(2)), fmt2(c(1)-c(2))));
end
if isfinite(c(3))
    w(fid, sprintf('作为对照，若假设未来真实电价提前已知，费用可降至 %s 元，与实际 %s 元之差即电价不确定性的代价。', fmt2(c(3)), fmt2(c(1))));
end
% ★ 2026-09-13 修正：原先这里写的是"可见对电价做随机建模是有价值的"，**与实测不符**。
%   两个消融口径（只用中心价格预测、不含价格情景）实测都比含情景的 SAA **更便宜**：
%   Q4-2P0 < Q4-2、Q4-3P0 < Q4-3。必须如实写出，不能反过来讲。
if isfinite(c(4)) && isfinite(c(1))
    w(fid, sprintf('若完全不建模电价风险、只按中心价格预测优化，费用为 %s 元，比含价格情景的 %s 元低 %s 元（%.2f%%）。', ...
        fmt2(c(4)), fmt2(c(1)), fmt2(c(1)-c(4)), 100*(c(1)/c(4)-1)));
end
if isfinite(c(5)) && isfinite(c(2))
    w(fid, sprintf('在引入日内价格更新后该差异收窄为 %s 元（%s 元 对 %s 元）。', ...
        fmt2(c(2)-c(5)), fmt2(c(5)), fmt2(c(2))));
end
if isfinite(c(4)) && isfinite(c(1))
    w(fid, '两处消融都指向同一结论：在本数据上，电价随机情景并未降低实现费用——中心预测已足够准，按情景对冲反而略偏保守。随机建模的价值在于对价格波动的稳健性（情景可覆盖负电价等极端情形），而不是降低这一条实测价格路径上的费用。');
end
w(fid, '程序同时给出电价预测的平均绝对误差与均方根误差，并报告日内峰价时刻与谷价时刻的预测偏差——储能调度真正关心的是"什么时候贵、什么时候便宜"，而不只是平均误差。');
fclose(fid);

fprintf('四份交付说明文本已写入 scripts/deliver_text/\n');
fprintf('MAKE_DELIVER_TEXT_DONE\n');
