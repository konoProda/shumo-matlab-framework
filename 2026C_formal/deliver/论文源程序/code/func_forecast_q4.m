function [phat, used_max, fb] = func_forecast_q4(price_m, pr1, K, d0)
%FUNC_FORECAST_Q4  问题四：外网电价的同星期回溯预测（只用历史实际价格）
%
%   与问题二负荷/光伏预测同一套规则、同一份实现：对目标日 τ，取严格早于
%   决策日 d0 的最近 K 个与 τ 同星期的日期，按同时段取均值。故此处不再另写算法，
%   直接把价格矩阵与附件1 的典型日电价曲线喂给问题二的预测器（它对输入是泛型的）。
%   冷启动（可用历史为空）自动回退到附件1 典型日曲线；1 月按已知数据处理时
%   决策日之前无历史，回退即为此曲线。
%
%   输入  price_m  D×T 实际电价（已按起始标签口径读入）元/kWh
%         pr1      T×1 附件1 典型日电价曲线（冷启动回退）
%         K        同星期回溯周数（建模口径 4）
%         d0       （可选）决策日索引；省略或给 [] 为逐日模式
%   输出  phat     (D-d0+1)×T（地平线模式）或 D×T（逐日模式）中心预测
%         used_max 各行实际引用的最晚历史日（信息泄漏自检用）
%         fb       是否走了冷启动回退

% 价格列与负荷/光伏列走同一支预测器：两个输出取其一即可，第二个位置传同一份数据。
[phat, ~, used_max, fb] = func_forecast_q2(price_m, price_m, pr1, pr1, K, d0);

end
