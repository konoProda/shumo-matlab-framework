function c = func_fig_pal(idx)
%func_fig_pal 固定调色板取色（2026-09-05 编程手图件规范，禁止散落硬编码 RGB）
% 输入: idx - 颜色序号（1 主蓝 ... 6 灰），越界按循环取
% 输出: c   - RGB 行向量（0–1）
% 规则: 单图 ≤4 色；同一变量/类别全论文同色；对比图"基准灰(6) + 最优强调色(4)"

P = [ 76 114 176;    % 1 主蓝（默认主色）
     221 132  82;    % 2 主橙
      85 168 104;    % 3 主绿
     196  78  82;    % 4 主红（强调）
     129 114 179;    % 5 紫
     140 140 140];   % 6 灰（基准/次要）
c = P(mod(idx - 1, size(P, 1)) + 1, :) / 255;
end
